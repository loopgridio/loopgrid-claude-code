#!/usr/bin/env python3
"""Real LoopGrid Core + deterministic Claude Code hook sandbox test (no Claude API).

Creates a new workspace and versioned sandbox-only amount policy to avoid
confusing unrelated evidence integrity in an existing shared workspace with
the validity of the evidence generated by this test. Never moves real money.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from urllib.parse import urlsplit
import sys
import tempfile
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import loopgrid_hook as lg



def main():
    cfg = lg.config()
    # Never create demo workspaces/policies on an unintended production origin.
    if urlsplit(cfg["base"]).hostname not in {"127.0.0.1", "localhost", "::1"}:
        raise RuntimeError("Sandbox test requires a loopback LoopGrid Core; refusing remote endpoint")
    cfg["mode"] = "enforce"

    cfg["state"] = Path(tempfile.mkdtemp(prefix="loopgrid-claude-e2e-")) / "hook.sqlite3"
    # Isolation matters: /decisions/<id>/verify verifies the ENTIRE workspace
    # chain, including prior decisions. An old key/tampered event in `default`
    # otherwise causes valid newly appended evidence to report valid=False.
    workspace = lg._api(cfg, "POST", "/api/v1/workspaces", {
        "name": "Claude Code isolated sandbox verification",
        "environment": "development", "privacy_mode": "proof_only",
    })
    wid = workspace.get("workspace_id")
    if not isinstance(wid, str) or not wid:
        raise RuntimeError("Core did not return a new sandbox workspace ID")
    cfg["workspace"] = wid
    cfg["policy"] = "claude-sandbox-refund"
    lg._api(cfg, "POST", f"/api/v1/workspaces/{wid}/policies", {
        "policy_id": cfg["policy"], "name": "Claude Code sandbox refund threshold",
        "version": "1.0", "active": True,
        "rule": {"type": "amount_threshold", "field": "amount",
                 "auto_approve_max": 500, "hard_limit": 1500, "currency": "USD"},
    })

    payload = {
        "session_id": "loopgrid-claude-code-e2e-" + uuid.uuid4().hex,
        "tool_use_id": "toolu_sandbox_" + uuid.uuid4().hex,
        "tool_name": "mcp__sandbox_payments__refund",
        "tool_input": {"amount": 25, "currency": "USD", "sandbox": True},
    }
    denied = lg.pre(payload, cfg)
    if denied is not None:
        raise RuntimeError("Core policy gate denied sandbox: " + json.dumps(denied))

    sandbox = {"receipt": "test_" + uuid.uuid4().hex, "status": "settled"}
    result = lg.post({**payload, "hook_event_name": "PostToolUse", "tool_response": sandbox}, cfg)
    if result is not None:
        raise RuntimeError("Post-hook failed: " + json.dumps(result))

    with lg.state_db(cfg) as db:
        decision_id, state = db.execute("SELECT decision_id,status FROM calls").fetchone()
    if state != "result_recorded":
        raise RuntimeError("Tool result was not durably recorded")

    if sandbox["status"] != "settled" or not sandbox["receipt"].startswith("test_"):
        raise RuntimeError("Sandbox outcome was not independently checked against the test receipt")
    lg._event(cfg, decision_id, "outcome_observed", {
        "status": "succeeded", "verified_against": "local_sandbox_receipt",
        "external_reference": sandbox["receipt"], "real_money_moved": False,
    }, "claude-code-sandbox:" + decision_id + ":outcome", "integration", "local-sandbox-verifier")

    verification = lg._api(cfg, "GET", f"/api/v1/decisions/{decision_id}/verify")
    detail = lg._api(cfg, "GET", f"/api/v1/decisions/{decision_id}")
    lifecycle = detail.get("summary", {}).get("lifecycle", {}).get("state")
    report = {
        "framework": "claude-code", "validation": "synthetic hook callbacks + real Core (isolated workspace)",
        "coreVersion": lg._api(cfg, "GET", "/ready").get("version"),
        "workspaceId": wid, "decisionId": decision_id,
        "verificationValid": verification.get("valid", False),
        "checkedEvents": verification.get("checked_events"),
        "totalWorkspaceEvents": verification.get("total_ledger_events"),
        "verificationFailures": verification.get("failures", []),
        "lifecycle": lifecycle, "sandboxExecutions": 1,
        "realMoneyMoved": False, "anthropicApiUsed": False,
    }
    print(json.dumps(report, indent=2))
    if not report["verificationValid"] or lifecycle != "evidence_complete":
        raise RuntimeError("Sandbox workspace evidence failed verification or lifecycle; inspect verificationFailures above")
    if not verification.get("checked_events"):
        raise RuntimeError("No events were verified")

    blocked = {**payload, "tool_use_id": "toolu_sandbox_" + uuid.uuid4().hex,
               "tool_input": {"amount": 2500, "currency": "USD", "sandbox": True}}
    deny_result = lg.pre(blocked, cfg)
    if not deny_result or deny_result.get("hookSpecificOutput", {}).get("permissionDecision") != "deny":
        raise RuntimeError("Core policy did not block the over-limit sandbox action")
    with lg.state_db(cfg) as db:
        blocked_status = db.execute("SELECT status FROM calls WHERE tool<>'' AND status='denied'").fetchone()
    if blocked_status is None:
        raise RuntimeError("Denied state was not durably recorded")
    # Check integrity once more after the blocked decision was appended.
    after_block = lg._api(cfg, "GET", f"/api/v1/decisions/{decision_id}/verify")
    if not after_block.get("valid"):
        raise RuntimeError("Workspace chain lost integrity after blocked decision: " + json.dumps(after_block.get("failures", [])))
    print("PASS: isolated real LoopGrid Core policy allow/deny + sandbox outcome + signed workspace verification")


if __name__ == "__main__":
    main()
